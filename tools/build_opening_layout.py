"""Generate locale opening centering data only after validating all local inputs."""
import argparse
import hashlib
import json
import math
from pathlib import Path, PurePosixPath

from audit_opening_layout import audit, read_tiles


def build(source, metadata, output):
    data = json.loads(metadata.read_text(encoding='utf8'))
    if data.get('schema') != 2 or not isinstance(data.get('layouts'), list):
        raise ValueError('unsupported opening metadata schema')
    entries, seen = [], set()
    for row in data['layouts']:
        layout, threshold = row.get('layout'), row.get('threshold')
        if type(layout) is not int or not 0 <= layout <= 9999 or layout in seen:
            raise ValueError('invalid or duplicate opening layout')
        if type(threshold) is not int or not 0 <= threshold <= 254:
            raise ValueError('invalid ink threshold')
        seen.add(layout)
        hashes = row.get('sha256', {})
        if not hashes:
            raise ValueError('opening source hashes are required')
        for name, expected in hashes.items():
            relative = PurePosixPath(name)
            if relative.is_absolute() or '..' in relative.parts or '\\' in name or ':' in name:
                raise ValueError('invalid source path')
            path = source.joinpath(*relative.parts)
            if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
                raise ValueError('opening source hash mismatch: ' + name)
        actual = audit(source, layout, threshold)
        actual_hashes = {key.replace('\\', '/'): value for key, value in actual['sha256'].items()}
        center = row.get('ink_center')
        if (not isinstance(center, list) or len(center) != 2
                or any(type(value) not in (int, float) or not math.isfinite(value) for value in center)):
            raise ValueError('invalid ink center')
        if (actual_hashes != hashes or actual['ink_center'] != center
                or list(actual['ink_xyxy']) != row.get('ink_xyxy')):
            raise ValueError('opening metadata does not match measured ink: ' + str(layout))
        bounds = row.get('source_tile_bounds')
        if (not isinstance(bounds, list) or len(bounds) != 4
                or any(type(value) is not int or value % 256 for value in bounds)
                or not (0 <= bounds[0] < bounds[2] <= 1024 and 0 <= bounds[1] < bounds[3] <= 768)):
            raise ValueError('invalid source tile bounds')
        for _, _, x, y, pixels in read_tiles(source, layout)[0]:
            if not (bounds[0] <= x < bounds[2] and bounds[1] <= y < bounds[3]):
                if pixels.convert('L').point(lambda value: 255 if value > threshold else 0).getbbox():
                    raise ValueError('source tile bounds exclude opening ink')
        entries.append((layout, *center, *bounds))
    lines = ['// Generated by tools/build_opening_layout.py; do not edit.',
             f'constexpr std::array<OpeningLayoutEntry,{len(entries)}> openingLayouts{{{{']
    lines.extend(f'    {{{layout}, {x:.1f}f, {y:.1f}f, {left}, {top}, {right}, {bottom}}},'
                 for layout, x, y, left, top, right, bottom in entries)
    lines.append('}};')
    # No output directories/files exist until every source and measurement passes.
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n', encoding='utf8')
    return len(entries)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--metadata', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    count = build(args.source, args.metadata, args.output)
    print(f'OPENING_LAYOUT_BUILD PASS layouts={count} source_hashes=exact ink_centers=measured game_started=false')
