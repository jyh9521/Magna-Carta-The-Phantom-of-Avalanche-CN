"""Generate bounded configuration display presets and the native hash allowlist."""
import argparse
import hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
RESOLUTIONS={'1080p':'1920x1080(-1)','2k':'2560x1440(-1)','4k':'3840x2160(-1)','auto':'display(-1)'}
def profiles():
    for resolution,scale in RESOLUTIONS.items():
        for mode in ('fullscreen','windowed','borderless'):
            for fps in (30,60):
                name=f'md3-{resolution}-{mode}-{fps}'
                # 窗口化使用原生引擎窗口标志，而不是虚构的兼容层枚举。
                fullscreen='exclusive' if mode=='fullscreen' else 'borderless'
                text=f'FullscreenMode = {fullscreen}\nDisplayAspectRatio = 16:9\nResolutionScale = {scale}\nLogLevel = info\nAltTabFix = noactivateapp(0)\nFpsLimiter = flipend({fps})\n'
                yield name,text.encode('ascii'),fps

def build(output):
    output.mkdir(parents=True,exist_ok=True)
    rows=[]
    for name,data,fps in profiles():
        (output/(name+'.ini')).write_bytes(data)
        rows.append('    {L"%s", "%s", true, %s},' % (name,hashlib.sha256(data).hexdigest(),'true' if fps==60 else 'false'))
    header='// Generated by tools/build_configuration_profiles.py; do not edit.\nstruct ConfigurationDisplayPreset { const wchar_t* name; const char* hash; bool wide; bool render60; };\nstatic const ConfigurationDisplayPreset configurationDisplayPresets[]={\n'+'\n'.join(rows)+'\n};\n'
    return header
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,required=True);parser.add_argument('--header',type=Path,required=True);a=parser.parse_args()
    a.header.write_text(build(a.output),encoding='utf8',newline='\n')
    print('CONFIGURATION_PROFILES PASS profiles=24')
